function build(i: DestinationInput): Destination {
  const faqs: Faq[] = [
    {
      question: `When is the best time to visit ${i.name}?`,
      answer: i.bestTime,
    },
    {
      question: `How do I get to ${i.name}?`,
      answer: i.gettingThere,
    },
    {
      question: `How many days do I need for ${i.name}?`,
      answer: i.duration,
    },
  ];
  return {
    slug: i.slug,
    name: i.name,
    countySlugs: i.counties,
    regionNote: i.regionNote,
    region: i.region,
    type: i.type,
    tagline: i.tagline,
    summary: i.summary,
    signatureExperience: i.signature,
    knownFor: i.knownFor,
    themes: i.themes,
    bestTime: i.bestTime,
    wildlife: i.wildlife,
    activities: i.activities,
    culture: i.culture,
    gettingThere: i.gettingThere,
    recommendedDuration: i.duration,
    travelTips: i.tips,
    faqs,
    relatedSlugs: i.related,
    coords: { lat: i.lat, lng: i.lng },
    image: {
      src: DESTINATION_STOCK_IMAGES[i.slug],
      alt: `${i.name}, Kenya — ${i.tagline.toLowerCase()}`,
    },
  };
}

